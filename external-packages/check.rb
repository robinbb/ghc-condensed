#!/usr/bin/env ruby
# frozen_string_literal: true

# Build and test the external package corpus with an in-tree compiler.
#
# Usage (inside `nix develop`, after `hadrian/build`):
#   check.rb [--tier N] [--all] [--build-root DIR] [--jobs N]
#            [--only pkg,...] [--no-tests] [--clean] [--no-keep-going]
#            [--write-project]
#
# Build products go to dist/<digest>/, where the digest is taken over the
# compiler binary and its package database, so a changed compiler always
# builds from scratch and an unchanged one reuses everything. Standalone
# projects (manifest entries with a `project` field) are solved and built
# on their own, under dist/<digest>/projects/NAME/.

require 'optparse'
require 'digest'
require 'fileutils'
require 'etc'
require 'json'
require 'open3'
require 'set'
require_relative 'lib/hackage'
require_relative 'lib/manifest'

ROOT = __dir__
REPO = File.expand_path('..', ROOT)
MAX_TIER = 3

# Progress lines must reach a redirected stdout as they happen.
$stdout.sync = true

# The corpus holds exactly one version of every package, so an upper
# bound between corpus packages can only reject the one plan there is;
# relaxing all upper bounds costs nothing and avoids a manual exception
# per lagging bound. Lower bounds still apply. Whether the code actually
# compiles against the newer dependency is what the build then tells us.
ALLOW_NEWER = 'all'

# A standalone project keeps the exact dependency versions that its own
# bounds select (recorded in its cabal.project.freeze), so only the
# bounds on packages the compiler ships are relaxed there: those versions
# are fixed by the compiler under test and cannot be chosen.
BOOT_ALLOW_NEWER = Hackage::BOOT.sort.map { |b| "*:#{b}" }.join(', ')

opts = { tier: 1, build_root: '_build', jobs: Etc.nprocessors, only: nil,
         tests: true, clean: false, keep_going: true, write_project: false }
OptionParser.new do |o|
  o.banner = 'Usage: check.rb [options]'
  o.on('--tier N', Integer, "Run tiers 1..N (default 1, max #{MAX_TIER})") { |v| opts[:tier] = v }
  o.on('--all', 'Run every tier') { opts[:tier] = MAX_TIER }
  o.on('--build-root DIR', 'Hadrian build root (default _build)') { |v| opts[:build_root] = v }
  o.on('--jobs N', Integer, 'Parallel package builds (default nproc)') { |v| opts[:jobs] = v }
  o.on('--only LIST', 'Comma-separated roots to restrict the run to') { |v| opts[:only] = v.split(',') }
  o.on('--no-tests', 'Build only') { opts[:tests] = false }
  o.on('--clean', 'Remove dist directories for other compilers') { opts[:clean] = true }
  o.on('--no-keep-going', 'Stop at the first build failure') { opts[:keep_going] = false }
  o.on('--write-project', 'Regenerate the cabal.project files and exit') { opts[:write_project] = true }
end.parse!
abort "check.rb: --tier must be 1..#{MAX_TIER}" unless (1..MAX_TIER).cover?(opts[:tier])

manifest = Manifest.load

def project_file(tier)
  tier == 1 ? 'cabal.project' : "cabal.project.tier#{tier}"
end

def project_dir(project)
  File.join(ROOT, 'projects', project)
end

# `package NAME` stanzas for the entries that need one.
def package_stanzas(entries)
  lines = []
  entries.select { |e| e['tests'] || e['flags'] }.sort_by { |e| e['name'] }.each do |e|
    lines << ''
    lines << "package #{e['name']}"
    lines << '  tests: True' if e['tests']
    lines << "  flags: #{e['flags']}" if e['flags']
  end
  lines
end

def write_projects(manifest)
  (1..MAX_TIER).each do |tier|
    pkgs = manifest.solvable(tier)
    lines = []
    lines << "-- Generated by check.rb from manifest.yaml for tier #{tier}."
    lines << '-- Do not edit; run `ruby check.rb --write-project` instead.'
    lines << 'packages:'
    pkgs.map { |e| e['path'] }.sort.each { |p| lines << "  #{p}" }
    lines << ''
    lines << 'tests: False'
    lines << 'benchmarks: False'
    lines << "index-state: #{manifest.index_state}" if manifest.index_state
    lines << "allow-newer: #{ALLOW_NEWER}"
    pkgs.filter_map { |e| e['constraints'] }.each { |c| lines << "constraints: #{c}" }
    lines += package_stanzas(pkgs)
    File.write(File.join(ROOT, project_file(tier)), lines.join("\n") + "\n")
  end
  manifest.projects.each do |proj|
    entries = manifest.project_entries(proj)
    prefix = "projects/#{proj}/"
    lines = []
    lines << "-- Generated by check.rb from manifest.yaml for the #{proj} project."
    lines << '-- Do not edit; run `ruby check.rb --write-project` instead.'
    lines << 'packages:'
    entries.map { |e| e['path'].delete_prefix(prefix) }.sort.each { |p| lines << "  #{p}" }
    lines << ''
    lines << '-- Private copies of the dependencies, at the versions recorded in'
    lines << '-- cabal.project.freeze; `add.rb --fetch` vendors them.'
    lines << 'optional-packages: vendored/*/*.cabal'
    lines << ''
    lines << 'tests: False'
    lines << 'benchmarks: False'
    lines << "index-state: #{manifest.index_state}" if manifest.index_state
    lines << "allow-newer: #{BOOT_ALLOW_NEWER}"
    entries.filter_map { |e| e['constraints'] }.each { |c| lines << "constraints: #{c}" }
    lines += package_stanzas(entries)
    FileUtils.mkdir_p(project_dir(proj))
    File.write(File.join(project_dir(proj), 'cabal.project'), lines.join("\n") + "\n")
  end
end

write_projects(manifest)
if opts[:write_project]
  puts 'check.rb: wrote cabal.project files'
  exit 0
end

build_root = File.expand_path(opts[:build_root], REPO)
ghc = File.join(build_root, 'stage1', 'bin', 'ghc')
ghc_pkg = File.join(build_root, 'stage1', 'bin', 'ghc-pkg')
pkg_cache = File.join(build_root, 'stage1', 'lib', 'package.conf.d', 'package.cache')
[ghc, ghc_pkg, pkg_cache].each do |f|
  abort "check.rb: #{f} not found; run hadrian/build first" unless File.exist?(f)
end

digest = Digest::SHA256.new
digest << File.binread(ghc)
digest << File.binread(pkg_cache)
key = digest.hexdigest[0, 12]
dist = File.join(ROOT, 'dist')
builddir = File.join(dist, key)
logdir = File.join(builddir, 'logs')
FileUtils.mkdir_p(logdir)
if opts[:clean]
  Dir.glob(File.join(dist, '*')).each do |d|
    next unless File.directory?(d) && File.basename(d) != key

    puts "removing #{d}"
    FileUtils.rm_rf(d)
  end
end
version = `#{ghc} --numeric-version`.strip
puts "compiler: #{ghc} (#{version}), digest #{key}"
puts "builddir: #{builddir}"

roots = manifest.roots(opts[:tier]).reject { |e| e['expected'] == 'unsolvable' }
roots.select! { |e| opts[:only].include?(e['name']) } if opts[:only]
abort 'check.rb: no roots selected' if roots.empty?

# Test suites that shell out to `ghc` (shake's documentation test, for
# one) must get the compiler under test, not whatever the shell has on
# PATH, and must see the corpus packages: PATH is prefixed with the
# build root's bin directory, and cabal writes a GHC environment file
# that a bare ghc picks up from any directory under the project's.
ENV['PATH'] = "#{File.dirname(ghc)}:#{ENV['PATH']}"

def cabal_common(project, builddir, ghc, ghc_pkg)
  ['cabal', '--offline', "--project-file=#{project}", "--builddir=#{builddir}",
   "--with-compiler=#{ghc}", "--with-hc-pkg=#{ghc_pkg}",
   '--write-ghc-environment-files=always']
end

# Run a command, streaming its output to a log file and echoing lines that
# match the filter. Returns [success, seconds].
def stream(cmd, log, echo: nil, env: {})
  t0 = Process.clock_gettime(Process::CLOCK_MONOTONIC)
  File.open(log, 'w') do |f|
    f.puts "$ #{env.map { |k, v| "#{k}=#{v} " }.join}#{cmd.join(' ')}"
    Open3.popen2e(env, *cmd, chdir: ROOT) do |_in, out, wait|
      out.each_line do |line|
        f.write(line)
        puts line if echo && line =~ echo
      end
      ok = wait.value.success?
      return [ok, Process.clock_gettime(Process::CLOCK_MONOTONIC) - t0]
    end
  end
end

# ---- build ----------------------------------------------------------------

# Build the given roots in one cabal project. Returns [status, blocked_by]
# where status maps every local package of the plan to ok, FAIL or
# blocked, and blocked_by lists the failed dependencies of a blocked one.
def build_project(common, label, roots, logdir, builddir, opts)
  cmd = common + ['build', "-j#{opts[:jobs]}"]
  cmd << '--keep-going' if opts[:keep_going]
  cmd += roots.map { |e| e['name'] }
  log = File.join(logdir, "build-#{label}.log")
  puts "building #{roots.size} root(s) for #{label}; log: #{log}"
  ok, secs = stream(cmd, log,
                    echo: /^(Building|Completed|Failed|Error|Warning: The package list|cabal: )|Could not resolve/)
  text = File.read(log)
  if text =~ /Could not resolve dependencies|cabal: Could not/
    puts text.lines.last(40).join
    abort "check.rb: dependency solving failed for #{label}; fix the manifest (mark packages unsolvable or add missing ones)"
  end
  # "Failed to build PKG-VER" is a library failure; "Failed to build exe:X
  # from PKG-VER" (or lib:, flib:) is also a build failure of PKG. Test
  # components ("test:X from PKG-VER") are left to the test phase.
  failed = text.scan(/Failed to build (?:(?:exe|lib|flib):[A-Za-z0-9-]+ from )?([A-Za-z0-9-]+?)-[0-9.]+(?:\.|\s|$)/).flatten.uniq
  # A non-zero exit with no package failure is normal when only test
  # components failed; abort only when cabal never started building.
  if !ok && failed.empty? && text !~ /^Building /
    puts text.lines.last(30).join
    abort "check.rb: cabal build failed before building anything for #{label}; see the log above"
  end

  # Local packages in the plan and their dependency graph, to find packages
  # that were never attempted because a dependency failed.
  plan_file = File.join(builddir, 'cache', 'plan.json')
  plan = File.exist?(plan_file) ? JSON.parse(File.read(plan_file)) : { 'install-plan' => [] }
  local = plan['install-plan'].select { |u| u['style'] == 'local' }
  by_id = local.to_h { |u| [u['id'], u] }
  deps_of = lambda do |u|
    ids = (u['depends'] || []) + (u['components'] || {}).values.flat_map { |c| c['depends'] || [] }
    ids.uniq.filter_map { |id| by_id[id] }.map { |d| d['pkg-name'] }
  end
  graph = Hash.new { |h, k| h[k] = [] }
  local.each { |u| graph[u['pkg-name']] |= deps_of.(u) - [u['pkg-name']] }
  planned = graph.keys
  blocked = Set.new
  loop do
    before = blocked.size
    planned.each do |p|
      next if failed.include?(p) || blocked.include?(p)

      blocked << p if graph[p].any? { |d| failed.include?(d) || blocked.include?(d) }
    end
    break if blocked.size == before
  end

  status = {}
  blocked_by = {}
  planned.each do |p|
    status[p] = if failed.include?(p) then 'FAIL'
                elsif blocked.include?(p) then 'blocked'
                else 'ok'
                end
    blocked_by[p] = graph[p].select { |d| failed.include?(d) || blocked.include?(d) } if blocked.include?(p)
  end
  puts format('%s build finished in %.0fs: %d ok, %d failed, %d blocked', label, secs,
              status.values.count('ok'), failed.size, blocked.size)
  [status, blocked_by]
end

build_status = {}
blocked_by = {}
# The cabal invocation (project file and build directory) each root
# belongs to, for its test runs.
entry_common = {}

tier_roots = roots.reject { |e| e['project'] }
unless tier_roots.empty?
  common = cabal_common(File.join(ROOT, project_file(opts[:tier])), builddir, ghc, ghc_pkg)
  status, bb = build_project(common, "tier#{opts[:tier]}", tier_roots, logdir, builddir, opts)
  build_status.merge!(status)
  blocked_by.merge!(bb)
  tier_roots.each { |e| entry_common[e['name']] = common }
end

# A standalone project's private dependency copies share names with
# corpus packages, so only its manifest entries are reported.
roots.select { |e| e['project'] }.group_by { |e| e['project'] }.each do |proj, proots|
  pbuild = File.join(builddir, 'projects', proj)
  FileUtils.mkdir_p(pbuild)
  common = cabal_common(File.join(project_dir(proj), 'cabal.project'), pbuild, ghc, ghc_pkg)
  status, bb = build_project(common, proj, proots, logdir, pbuild, opts)
  members = manifest.project_entries(proj).map { |e| e['name'] }
  build_status.merge!(status.slice(*members))
  blocked_by.merge!(bb.slice(*members))
  proots.each { |e| entry_common[e['name']] = common }
end

# ---- tests ----------------------------------------------------------------
test_status = {}
test_secs = {}
if opts[:tests]
  roots.select { |e| e['tests'] }.each do |e|
    name = e['name']
    unless build_status[name] == 'ok'
      test_status[name] = 'skipped'
      next
    end
    # Per-package environment for the test run, e.g. CI=true where the
    # package's own CI relies on it to select tests.
    env = (e['env'] || {}).to_h { |k, v| [k.to_s, v.to_s] }
    # `test_runs` lists argument strings for the test executable; each
    # becomes one `cabal test --test-options=...` run, and all must pass.
    # Used where a package's harness runs one named test per invocation
    # and the full suite is too slow or too broad for a sanity check.
    runs = e['test_runs'] ? e['test_runs'].map(&:to_s) : [nil]
    total = 0.0
    status = 'pass'
    runs.each_with_index do |args, i|
      log = File.join(logdir, runs.size > 1 ? "test-#{name}-#{i + 1}.log" : "test-#{name}.log")
      puts "testing #{name}#{args ? " (#{args})" : ''}; log: #{log}"
      cmd = entry_common[name] + ['test', '--test-show-details=direct']
      cmd << "--test-options=#{args}" if args
      cmd << name
      ok, secs = stream(cmd, log, echo: /^(Test suite .* (passed|failed)|Failed|Error)/, env: env)
      total += secs
      status = 'FAIL' unless ok
    end
    test_status[name] = status
    test_secs[name] = total
  end
end

# ---- summary --------------------------------------------------------------
unexpected = []
rows = []
manifest.packages.select { |e| e['tier'] <= opts[:tier] }.sort_by { |e| [e['tier'], e['name'].downcase] }.each do |e|
  name = e['name']
  b = e['expected'] == 'unsolvable' ? 'unsolvable' : (build_status[name] || '-')
  t = test_status[name] || '-'
  exp = e['expected']
  verdict =
    if b == 'FAIL' && exp != 'build-failure' then 'UNEXPECTED build failure'
    elsif b == 'ok' && exp == 'build-failure' then 'unexpected build success'
    elsif exp == 'flaky' && t != '-' then 'known flaky'
    elsif t == 'FAIL' && exp != 'test-failure' then 'UNEXPECTED test failure'
    elsif t == 'pass' && exp == 'test-failure' then 'unexpected test success'
    elsif b == 'FAIL' || t == 'FAIL' then 'known'
    elsif b == 'blocked' then "blocked by #{blocked_by[name].join(', ')}"
    else ''
    end
  unexpected << [name, verdict] unless verdict.empty? || verdict.start_with?('known') || verdict.start_with?('blocked')
  rows << [name, e['tier'], b, t, test_secs[name] ? format('%.0fs', test_secs[name]) : '', verdict]
end
w = rows.map { |r| r[0].size }.max
puts
puts format("%-#{w}s tier build      tests   time   note", 'package')
rows.each do |r|
  next if r[2] == '-' && r[3] == '-' && r[5].empty?

  puts format("%-#{w}s %-4d %-10s %-7s %-6s %s", *r)
end
results = { 'compiler' => version, 'digest' => key, 'tier' => opts[:tier],
            'build' => build_status, 'tests' => test_status, 'unexpected' => unexpected }
File.write(File.join(builddir, "results-tier#{opts[:tier]}.json"), JSON.pretty_generate(results))
puts
if unexpected.empty?
  puts 'check.rb: OK, no unexpected results'
  exit 0
else
  puts "check.rb: #{unexpected.size} unexpected result(s):"
  unexpected.each { |n, v| puts "  #{n}: #{v}" }
  exit 1
end
